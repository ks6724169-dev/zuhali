def slugify(text: str) -> str:
    cleaned = re.sub(r'[^a-zA-Z0-9\s-]', '', text).strip().lower()
    slug = re.sub(r'[\s_]+', '-', cleaned)
    return slug[:32] if slug else "my-project"

def extract_project_name(prompt: str) -> str:
    p = prompt.lower()
    # Common triggers
    for kw in ["create a", "build a", "make a", "generate a", "develop a", "create", "build", "make"]:
        if kw in p:
            parts = p.split(kw, 1)[1].strip()
            first_clause = re.split(r'[,.\n;]|with|using|for|in', parts)[0].strip()
            if first_clause:
                slug = slugify(first_clause)
                if slug and len(slug) > 2:
                    return slug
    return slugify(prompt[:25]) or "zuhali-app"

